CREATE TABLE ticket (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200)  NOT NULL,
    description TEXT          NOT NULL,
    status      VARCHAR(30)   NOT NULL DEFAULT 'OPEN',
    priority    VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
    assignee    VARCHAR(100),
    version     BIGINT        NOT NULL DEFAULT 0,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ticket_status ON ticket (status);
CREATE INDEX idx_ticket_priority ON ticket (priority);
CREATE INDEX idx_ticket_created_at ON ticket (created_at DESC);

CREATE TABLE ticket_comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT       NOT NULL REFERENCES ticket (id) ON DELETE CASCADE,
    body       TEXT         NOT NULL,
    author     VARCHAR(100) NOT NULL DEFAULT 'Agent',
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ticket_comment_ticket_id ON ticket_comment (ticket_id);
